import { Head, Link, usePage } from "@inertiajs/react";
import { AppLayout } from "@/components/layout";
import { PageHeader } from "@/components/layout";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { BarChart, FileText, ClipboardList, TrendingUp, Users, Package } from "lucide-react";

interface Report {
  id: number;
  name: string;
  type: string;
  status: string;
  generated_at: string;
  created_by: string;
}

const REPORT_CARDS = [
  {
    title: "Production Efficiency Report",
    description: "Machine utilization, output vs plan, and efficiency trends.",
    icon: <BarChart size={20} />,
    color: "bg-sky-50 text-sky-700",
  },
  {
    title: "Inventory Valuation Report",
    description: "Current stock value by warehouse and category.",
    icon: <Package size={20} />,
    color: "bg-indigo-50 text-indigo-700",
  },
  {
    title: "Quality Yield Report",
    description: "Pass/fail rates, defects, and quality trends.",
    icon: <ClipboardList size={20} />,
    color: "bg-emerald-50 text-emerald-700",
  },
  {
    title: "Sales Performance Report",
    description: "Revenue by customer, product, and salesperson.",
    icon: <TrendingUp size={20} />,
    color: "bg-rose-50 text-rose-700",
  },
  {
    title: "Workforce Utilization",
    description: "Employee productivity and labor cost analysis.",
    icon: <Users size={20} />,
    color: "bg-purple-50 text-purple-700",
  },
  {
    title: "Financial Summary",
    description: "P&L, balance sheet, and cash flow overview.",
    icon: <FileText size={20} />,
    color: "bg-amber-50 text-amber-700",
  },
];

export default function Reports() {
  const { props: data } = usePage() as any;
  const reports: Report[] = data?.reports || [];

  return (
    <AppLayout title="Reports">
      <PageHeader
        title="Reports"
        subtitle="Operational and financial reports for management"
        breadcrumbs={[{ label: "Reports", href: "/reports" }]}
      />

      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
        {REPORT_CARDS.map((card) => (
          <Card key={card.title} className="cursor-pointer hover:shadow-md transition-shadow">
            <CardHeader className="flex-row items-center justify-between pb-4">
              <CardTitle className="text-base font-semibold text-slate-900">{card.title}</CardTitle>
              <div className={`rounded-lg p-2 ${card.color}`}>{card.icon}</div>
            </CardHeader>
            <CardContent className="p-5 pt-0">
              <p className="text-sm text-slate-600">{card.description}</p>
            </CardContent>
            <CardFooter>
              <Link
                href="/accounting/trial-balance"
                className="inline-flex items-center gap-1 text-xs font-medium text-factory-600 hover:text-factory-700"
              >
                Generate report <span className="text-factory-500">→</span>
              </Link>
            </CardFooter>
          </Card>
        ))}
      </div>

      {reports.length > 0 && (
        <div className="mt-10">
          <h2 className="text-lg font-semibold text-slate-900 mb-4">Recent Reports</h2>
          <DataTableUnstyled
            title="Generated Reports"
            columns={[
              { key: "name", label: "Report Name" },
              { key: "type", label: "Type" },
              { key: "status", label: "Status" },
              { key: "generated_at", label: "Generated At" },
              { key: "created_by", label: "Generated By" },
            ]}
            data={reports}
          />
        </div>
      )}
    </AppLayout>
  );
}

function DataTableUnstyled(props: any) {
  const { columns, data } = props;
  return (
    <div className="overflow-hidden rounded-xl border border-slate-200 bg-white shadow-sm">
      <table className="w-full text-sm">
        <thead>
          <tr className="border-b border-slate-200 bg-slate-50/80">
            {columns.map((col: any) => (
              <th key={col.key} className="whitespace-nowrap px-5 py-3 text-[11px] font-semibold uppercase tracking-wider text-slate-500 text-left">
                {col.label}
              </th>
            ))}
          </tr>
        </thead>
        <tbody className="divide-y divide-slate-100">
          {data.map((row: any, index: number) => (
            <tr key={index} className="transition-colors hover:bg-slate-50/70">
              {columns.map((col: any) => (
                <td key={col.key} className="whitespace-nowrap px-5 py-3 text-slate-700">
                  {row[col.key] ?? "—"}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
